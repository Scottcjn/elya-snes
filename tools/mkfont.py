CELL = 8
GW, GH = 5, 7


def bitmap(ch):
    """The glyph as an 8x8 grid of ink indices (0 paper, 1 letter, 2 shadow)."""
    rows = GLYPHS[ch].split()
    assert len(rows) == GH, "%r has %d rows, want %d" % (ch, len(rows), GH)
    for r in rows:
        assert len(r) == GW, "%r row %r is %d wide, want %d" % (ch, r, len(r), GW)
    g = [[0] * CELL for _ in range(CELL)]
    for y in range(GH):
        for x in range(GW):
            if rows[y][x] == '#':
                g[y][x] = 1
    # drop shadow: one pixel down-right of every ink pixel, where empty
    for y in range(CELL - 1, 0, -1):
        for x in range(CELL - 1, 0, -1):
            if g[y][x] == 0 and g[y - 1][x - 1] == 1:
                g[y][x] = 2
    return g


def encode2bpp(g):
    """SNES 2bpp: planes 0 and 1 interleaved per row, 16 bytes."""
    b = bytearray()
    for y in range(CELL):
        p0 = p1 = 0
        for x in range(CELL):
            v = g[y][x]
            p0 |= (v & 1) << (7 - x)
            p1 |= ((v >> 1) & 1) << (7 - x)
        b += bytes([p0, p1])
    return bytes(b)


def main(out_prefix):
    chars = [chr(c) for c in range(0x20, 0x80)]
    missing = [c for c in chars if c not in GLYPHS]
    if missing:
        print("missing glyphs: %r" % missing, file=sys.stderr)
        return 1
    chr_data = bytearray()
    for c in chars:
        chr_data += encode2bpp(bitmap(c))
    open(out_prefix + '.chr', 'wb').write(chr_data)

    # preview: the whole set, 16 columns, at 4x so a bad row is obvious
    from PIL import Image
    cols, rows = 16, (len(chars) + 15) // 16
    im = Image.new('RGB', (cols * CELL, rows * CELL), (24, 24, 40))
    px = im.load()
    ink = {1: (255, 255, 255), 2: (70, 70, 120)}
    for i, c in enumerate(chars):
        g = bitmap(c)
        ox, oy = (i % cols) * CELL, (i // cols) * CELL
        for y in range(CELL):
            for x in range(CELL):
                if g[y][x]:
                    px[ox + x, oy + y] = ink[g[y][x]]
    im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(
        out_prefix + '_preview.png')
    print("font: %d glyphs, %d bytes of 2bpp CHR (%.1f KB)"
          % (len(chars), len(chr_data), len(chr_data) / 1024))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else 'assets/font'))
